#!/usr/bin/env python3
"""Generate a signature-compatible, silent browser replacement for Arc Soloud JNI."""

import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "Arc/arc-core/src/arc/audio/Soloud.java"
TARGET = ROOT / "browser-game/src/main/java/arc/audio/Soloud.java"
METHOD = re.compile(r"static native\s+([\w.\[\]]+)\s+(\w+)\(([^;]*)\)\s*;")


def default_statement(return_type: str) -> str:
    if return_type == "void":
        return ""
    if return_type == "boolean":
        return "return false;"
    if return_type == "String":
        return 'return "browser-silent";'
    if return_type in {"float", "double"}:
        return "return 0f;" if return_type == "float" else "return 0d;"
    return "return 0;"


def main() -> None:
    methods = METHOD.findall(SOURCE.read_text(encoding="utf-8"))
    if len(methods) != 66:
        raise RuntimeError(f"Expected 66 Soloud native methods, found {len(methods)}")

    lines = [
        "// Generated by scripts/generate-silent-soloud.py. Do not edit manually.",
        "package arc.audio;",
        "",
        "/** Browser-only no-op replacement for the SoLoud JNI surface. */",
        "public final class Soloud{",
        "    private Soloud(){}",
        "",
    ]
    for return_type, name, parameters in methods:
        statement = default_statement(return_type)
        suffix = f" {statement}" if statement else ""
        lines.append(f"    static {return_type} {name}({parameters}){{{suffix} }}")
    lines.append("}")
    lines.append("")

    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated {TARGET.relative_to(ROOT)} with {len(methods)} silent methods.")


if __name__ == "__main__":
    main()
